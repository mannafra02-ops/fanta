const key = s => String(s || "").normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim().replace(/\s+/g, " ");

export function officialPlayerIndex(players) {
  return new Map(players.filter(g => g?.fcId && !g.out).map(g => [String(g.fcId), g]));
}

// Conserva gli acquisti identificati anche se il listone non è disponibile:
// id -1 non viene mostrato né usato finché non si ritrova l'ID ufficiale.
export function remapLeagueAcquisitions(rows, players) {
  const official = officialPlayerIndex(players);
  return rows.flatMap(row => row.fcId
    ? [{ ...row, id: official.get(String(row.fcId))?.id ?? -1 }]
    : players[row.id] && !players[row.id].out ? [row] : []);
}

export function planLeagueImport(market, own, players, rosters = LEAGUE_ROSTERS) {
  const official = officialPlayerIndex(players);
  const names = [...market.nomi];
  let teamCount = market.n;
  const existing = market.altri;
  const reserved = new Set([0]);
  const assigned = new Map();
  const matches = rosters.map(({ name }) => {
    const found = Array.from({ length: market.n - 1 }, (_, i) => i + 1).filter(t => key(names[t]) === key(name));
    if (found.length > 1) throw new Error(`Più squadre si chiamano ${name}: rinominale prima di importare.`);
    if (found.length) reserved.add(found[0]);
    return found[0];
  });
  const missing = [];
  const rows = [];
  rosters.forEach(({ name, players: roster }, i) => {
    let team = matches[i];
    if (team === undefined) {
      team = Array.from({ length: teamCount - 1 }, (_, j) => j + 1).find(t => !reserved.has(t)
        && (!key(names[t]) || /^squadra \d+$/.test(key(names[t])))
        && !existing.some(row => row.team === t));
      if (team === undefined) {
        if (teamCount >= 14) throw new Error("Non ci sono posti liberi: rinomina le squadre già presenti con i nomi delle rose da importare.");
        team = teamCount++;
      }
    }
    reserved.add(team);
    names[team] = name;
    for (const [officialId, label, role, , prezzo] of roster) {
      const g = official.get(String(officialId));
      if (!g || g.r !== role) { missing.push(label); continue; }
      if (assigned.has(g.id)) throw new Error(`Il giocatore ${label} compare in più rose.`);
      if (!Number.isInteger(prezzo) || prezzo < 1) throw new Error(`Costo non valido: ${label}.`);
      assigned.set(g.id, team);
      rows.push({ id: g.id, fcId: String(officialId), prezzo, team });
    }
  });
  if (missing.length) throw new Error(`Listone non allineato: ${missing.length} giocatori non abbinati (${missing.slice(0, 4).join(", ")}). Nessuna rosa è stata modificata.`);
  const teamName = t => names[t] || (t === 0 ? "La tua rosa" : `Squadra ${t+1}`);
  const moves = [...own.map(row => ({ ...row, team: 0 })), ...existing].flatMap(row => {
    const team = assigned.get(row.id);
    return team === undefined || team === row.team ? [] :
      [{ id: row.id, player: players[row.id]?.n, from: teamName(row.team), to: teamName(team), own: row.team === 0 }];
  });
  const replacing = existing.filter(row => reserved.has(row.team)).length;
  const retained = existing.filter(row => !reserved.has(row.team) && !assigned.has(row.id));
  return {
    moves, replacing, count: rows.length,
    own: own.filter(row => !assigned.has(row.id)),
    market: { ...market, n: teamCount, nomi: names, altri: [...retained, ...rows], roseImportVersion: LEAGUE_ROSTER_VERSION }
  };
}
